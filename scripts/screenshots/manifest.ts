import { createHash } from 'crypto'

/**
 * Every capture's SHA-256, by scenario, then step, then theme.
 *
 * The PNGs themselves aren't committed: they live on the image host, named by
 * this hash. The manifest is what is committed, so `git diff` on it is the
 * visual-regression check: captures are byte-identical within one
 * environment, so a changed hash is a changed image.
 *
 * A scenario that never calls `shot` is captured once, under the step `""`.
 */
export type Manifest = Record<string, Record<string, Record<string, string>>>

/** Where captures are served from, by the SHA-256 of their bytes. */
export const CDN_ORIGIN = 'https://cdn.isaacshea.com'

export function cdnUrl(sha256: string): string {
  return `${CDN_ORIGIN}/i/${sha256}.png`
}

export function sha256Hex(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex')
}

/** `<scenario>-<theme>.png`, or `<scenario>-<step>-<theme>.png`. */
export function captureFileName(scenario: string, step: string, theme: string): string {
  return step ? `${scenario}-${step}-${theme}.png` : `${scenario}-${theme}.png`
}

/** Records one capture into `manifest`, in place. */
export function recordCapture(
  manifest: Manifest,
  capture: { scenario: string; step: string; theme: string; sha256: string }
): void {
  const steps = (manifest[capture.scenario] ??= {})
  const themes = (steps[capture.step] ??= {})
  themes[capture.theme] = capture.sha256
}

/**
 * Folds one run's captures into the manifest it started from.
 *
 * A scenario that ran replaces its entry wholesale, so a step it no longer
 * captures drops out. A scenario that didn't run (`npm run screenshot --
 * shell` runs one) keeps its previous entry. A scenario that no longer exists
 * drops out, so a renamed or deleted one doesn't linger.
 */
export function mergeManifest(
  previous: Manifest,
  fresh: Manifest,
  knownScenarios: readonly string[]
): Manifest {
  const merged: Manifest = {}
  for (const name of knownScenarios) {
    const entry = fresh[name] ?? previous[name]
    if (entry) merged[name] = entry
  }
  return merged
}

const SHA256 = /^[0-9a-f]{64}$/

/** Parses a manifest file, failing loudly on anything that isn't one. */
export function parseManifest(text: string): Manifest {
  const data: unknown = JSON.parse(text)
  const isObject = (value: unknown): value is Record<string, unknown> =>
    typeof value === 'object' && value !== null && !Array.isArray(value)

  if (!isObject(data)) throw new Error('Screenshot manifest must be a JSON object')
  for (const [scenario, steps] of Object.entries(data)) {
    if (!isObject(steps)) throw new Error(`Manifest entry "${scenario}" must be an object`)
    for (const [step, themes] of Object.entries(steps)) {
      if (!isObject(themes)) {
        throw new Error(`Manifest entry "${scenario}" step "${step}" must be an object`)
      }
      for (const [theme, hash] of Object.entries(themes)) {
        if (typeof hash !== 'string' || !SHA256.test(hash)) {
          throw new Error(`Manifest hash for ${captureFileName(scenario, step, theme)} is invalid`)
        }
      }
    }
  }
  return data as Manifest
}

/**
 * The manifest as committed: every level's keys sorted, so the file depends
 * only on what was captured and a diff names exactly the captures that moved.
 */
export function serializeManifest(manifest: Manifest): string {
  const sorted = <T>(record: Record<string, T>, map: (value: T) => unknown): object =>
    Object.fromEntries(
      Object.keys(record)
        .sort()
        .map((key) => [key, map(record[key])])
    )

  const ordered = sorted(manifest, (steps) =>
    sorted(steps, (themes) => sorted(themes, (hash) => hash))
  )
  return `${JSON.stringify(ordered, null, 2)}\n`
}

export const KEY_SCREENS_START = '<!-- key-screens:start (generated by npm run screenshot) -->'
export const KEY_SCREENS_END = '<!-- key-screens:end -->'

/**
 * The key-screens table: one row per captured step of every scenario marked
 * `key`, each theme linked by its hash on the image host. A key scenario the
 * manifest doesn't have yet is skipped rather than shown as a broken image.
 */
export function renderKeyScreens(
  manifest: Manifest,
  keyScenarios: readonly { name: string; key: string }[],
  themes: readonly string[]
): string {
  const header = [
    `| Capture | What it shows | ${themes.map(capitalise).join(' | ')} |`,
    `| --- | --- | ${themes.map(() => '---').join(' | ')} |`
  ]

  const rows = keyScenarios.flatMap(({ name, key }) => {
    const steps = manifest[name]
    if (!steps) return []
    return Object.keys(steps)
      .sort()
      .map((step, index) => {
        const label = step ? `\`${name}\` · \`${step}\`` : `\`${name}\``
        const caption = index === 0 ? key.replaceAll('|', '\\|') : ''
        const images = themes.map((theme) => {
          const hash = steps[step][theme]
          const alt = [name, step, theme].filter(Boolean).join(', ')
          return hash ? `![${alt}](${cdnUrl(hash)})` : '—'
        })
        return `| ${label} | ${caption} | ${images.join(' | ')} |`
      })
  })

  return [...header, ...rows].join('\n')
}

/** Swaps the generated block in `readme` for `generated`, keeping the markers. */
export function replaceKeyScreens(readme: string, generated: string): string {
  const start = readme.indexOf(KEY_SCREENS_START)
  const end = readme.indexOf(KEY_SCREENS_END)
  if (start === -1 || end === -1 || end < start) {
    throw new Error(
      `docs/screenshots/README.md is missing the "${KEY_SCREENS_START}" ... ` +
        `"${KEY_SCREENS_END}" markers the key-screens table is generated between`
    )
  }
  return (
    readme.slice(0, start + KEY_SCREENS_START.length) + `\n\n${generated}\n\n` + readme.slice(end)
  )
}

function capitalise(word: string): string {
  return word.charAt(0).toUpperCase() + word.slice(1)
}
